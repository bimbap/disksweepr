/**
 * Expands Windows environment variables in paths (e.g. %TEMP%, %LOCALAPPDATA%)
 */
export function expandEnvVars(rawPath: string): string {
  return rawPath.replace(/%([^%]+)%/g, (_, n) => {
    const key = n.toUpperCase();
    if (key === 'TEMP' || key === 'TMP') {
      return process.env.TEMP || os.tmpdir();
    }
    if (key === 'LOCALAPPDATA') {
      return process.env.LOCALAPPDATA || path.join(os.homedir(), 'AppData', 'Local');
    }
    if (key === 'APPDATA') {
      return process.env.APPDATA || path.join(os.homedir(), 'AppData', 'Roaming');
    }
    if (key === 'USERPROFILE' || key === 'HOME') {
      return os.homedir();
    }
    if (key === 'SYSTEMROOT' || key === 'WINDIR') {
      return process.env.SystemRoot || 'C:\\Windows';
    }
    if (key === 'SYSTEMDRIVE') {
      return process.env.SystemDrive || 'C:';
    }
    if (key === 'PROGRAMDATA') {
      return process.env.ProgramData || 'C:\\ProgramData';
    }
    if (key === 'PROGRAMFILES(X86)') {
      return process.env['ProgramFiles(x86)'] || 'C:\\Program Files (x86)';
    }
    if (key === 'PROGRAMFILES') {
      return process.env.ProgramFiles || 'C:\\Program Files';
    }
    return process.env[n] || '';
  });
}

